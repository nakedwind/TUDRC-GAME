assert.equal(canApply([['medkit', -1], ['gear', 1]]), true);
assert.equal(gain('gear', 21), 20);
bag.set('extra', 1);
assert.equal(bag.get('extra') || 0, 0);
// 舊存檔超量仍保留；容量回到限制內以前不能增加物品。
vm.runInContext("Map.prototype.set.call(supplyInventory, 'legacy', 800)", ctx);
assert.equal(bag.get('legacy'), 800);
assert.equal(room('legacy'), 0);
