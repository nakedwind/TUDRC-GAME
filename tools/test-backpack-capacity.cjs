assert.equal(ctx.shopRoom({ id: 'a' }), 20);
bag.set('medkit', 680);
assert.equal(ctx.shopRoom({ id: 'a' }), 0);
// 清單確實拆成 20／20／1，並顯示 35 格。
const counter = {}, grid = { classList: { add() {}, remove() {} }, innerHTML: '' };
ctx.MAP_SAFE = true; ctx.G = { player: {} };
vm.runInContext(source.slice(source.indexOf('let backpackCampContext'), source.indexOf('let bagDropQty')), ctx);
ctx.document = { getElementById: id => id === 'backpackCount' ? counter : { innerHTML: '' } };
ctx.backpackEl = {};
ctx.backpackGrid = grid;
ctx.backpackTab = 'consumable'; ctx.backpackSel = null;
ctx.WEAPON_TAB = { id: 'weapon' }; ctx.GEAR_TAB = { id: 'equip' };
ctx.BAG_ICON = {}; ctx.BAG_MIN_SLOTS = 35;
ctx.window = { innerWidth: 1200 }; ctx.requestAnimationFrame = fn => fn();
ctx.renderBackpackDetail = () => {};
ctx.ownedItems = () => [{ id: 'battery', name: '電池', category: 'consumable', image: '' }];
bag.clear(); bag.set('battery', 41);
vm.runInContext(source.slice(source.indexOf('function renderBackpack()'), source.indexOf('function gearCellHtml(')), ctx);
ctx.renderBackpack();
assert.equal(counter.textContent, '3 / 35 格');
assert.equal((grid.innerHTML.match(/<b>20<\/b>/g) || []).length, 2);
assert.equal((grid.innerHTML.match(/<b>1<\/b>/g) || []).length, 1);
assert.equal((grid.innerHTML.match(/bag-cell empty/g) || []).length, 32);
// 各分類獨立 35 格，某一分類滿了不影響其他分類。
ctx.SUPPLIES = [{ id: 'medkit', kind: 'medical' }, { id: 'snack', kind: 'snack' }];
bag.clear();
assert.equal(gain('medkit', 700), 700);
assert.equal(gain('burning-shard', 700), 700);
assert.equal(gain('snack', 700), 700);
assert.equal(used(bag, 'consumable'), 35);
assert.equal(used(bag, 'key'), 35);
assert.equal(used(bag, 'squadgear'), 35);
assert.equal(room('battery'), 0);
assert.equal(room('pure-shard'), 0);
assert.equal(gain('snack', 1), 1);
assert.equal(room('snack'), Infinity);
bag.set('snack', 680);
assert.equal(gain('snack', 20), 20);
assert.equal(canApply([['snack', -20]]), true);
