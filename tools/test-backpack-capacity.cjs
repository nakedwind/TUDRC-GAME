const node = selector => {
  if (!nodes.has(selector)) nodes.set(selector, { innerHTML: '', scrollTop: 0, classList: { add() {}, remove() {} }, querySelector() { return { complete: false }; }, focus() {} });
  return nodes.get(selector);
};
