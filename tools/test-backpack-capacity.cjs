assert.equal(bag.get('legacy'), 799);
// 所有物品分類皆已遷移。
assert.equal(ctx.items.find(i => i.id === 'battery').category, 'consumable');
assert(ctx.items.filter(i => i.id.endsWith('-shard')).every(i => i.category === 'key'));
assert(!ctx.categories.some(c => c.id === 'material' || c.id === 'gift'));
assert.equal(ctx.categories.find(c => c.id === 'consumable').name, '物品');
// 購物車必須把其他品項將占用的格數一起計算。
ctx.shopCart = new Map([['a', 20], ['b', 20]]);
ctx.shopItemById = id => ({ id });
